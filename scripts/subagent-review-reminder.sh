#!/bin/bash
# UserPromptSubmit hook。サブエージェントや別セッションからの報告（Subagent hand-back、task-notification、
# agent-message、cross-session-message）が届いたときだけ、報告を受け取ったエージェントがユーザーへ渡す前に
# 報告を確かめる手順を差し込む。ユーザー自身の発話では何も出さない。
# 手順の本文はこのスクリプトに置き、CLAUDE.mdにはこのhookがあることを一行で書く。
input=$(cat)
if printf '%s' "$input" | grep -qE 'Subagent hand-back|<task-notification>|agent-message from=|cross-session-message from='; then
  cat <<'JSON'
{"hookSpecificOutput":{"hookEventName":"UserPromptSubmit","additionalContext":"【サブエージェントの報告を受け取ったとき】いま届いた報告の中身は、あなた（報告を受け取った司令塔のエージェント）が確かめるまで、正しいとは限りません。そのため、そのままユーザーに渡してはいけません。あなたは、報告をユーザーに渡す前に次の四つを検査してください。(1) 報告が挙げている論点と判断事項を、プロジェクトの決定の記録と既存の文書・コードと照合してください。そして、既に結論が出ている事項や前提認識に相違のある事項については、あなたがユーザーに渡す内容から外すか、留保を置いて提示する。(2) 報告から事実と推論とを峻別してください。報告内容のうち「〜と読める」「〜の可能性がある」と書かれたものは推論なので、根拠を確かめないままには、それを事実としてはユーザーに伝えてはいけません。あなたが自分で確かめられることは、あなたが確かめ、それができない場合には判断を保留するべきです。(3) 報告が「問題なし」のような内容であっても、それを報告したサブエージェントが問題を握りつぶしている可能性を考慮し、健全な疑いを持ってください。AI Agentはしばしば、観測上の違和感などに対して、自らの恣意的な解釈で無理に合理化された結論を出そうとすることがあります（認知的不協和の安易な解消）。そうした気配のある報告文の場合、あなた＝司令塔の側で適切な調査や推論をし直してください。(4) あなたがユーザーに判断を求めるのは、(1)から(3)を済ませてもなお残るものと心得てください。つまり、ユーザーに渡す前に潰せる論点は潰し切り、ユーザーにしか決められない論点だけに絞り込み、明らかなノイズは排除し、また断言できないことを不用意に断言しないでください。"}}
JSON
fi
exit 0
